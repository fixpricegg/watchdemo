class StorageUnitTests(unittest.TestCase):
    def test_migration_checksum_is_portable_across_windows_and_linux(self):
        with tempfile.TemporaryDirectory() as root:
            path = Path(root) / "migration.sql"
            path.write_bytes(b"SELECT 1;\nSELECT 2;\n")
            checksum = migration_checksum(path)
            path.write_bytes(b"SELECT 1;\r\nSELECT 2;\r\n")
            self.assertEqual(migration_checksum(path), checksum)

    def test_snapshot_supports_analyzer_numpy_values_and_tick_keys(self):
        value = {100: np.array([1.5, 2.0]), "stats": np.int64(3),
                 "nan": float("nan"), "inf": np.float64(float("inf"))}
        self.assertEqual(json_snapshot(value), {"100": [1.5, 2.0], "stats": 3, "nan": None, "inf": None})

    def test_repository_requires_explicit_connection(self):
        with self.assertRaisesRegex(RuntimeError, "WATCHDEMO_DATABASE_URL"):
            Repository(None)

    def test_invalid_schema_is_rejected(self):
        with self.assertRaises(ValueError):
            Repository("unused", schema="public; DROP SCHEMA public")

    def test_analyze_request_requires_identifier(self):
        with self.assertRaises(ValueError):
            AnalyzeRequest(steamid="123")

    def test_import_and_factory_do_not_create_upload_directory(self):
        with tempfile.TemporaryDirectory() as root:
            directory = Path(root) / "does-not-exist"
            create_app(upload_dir=directory)
            self.assertFalse(directory.exists())


@unittest.skipUnless(os.environ.get("WATCHDEMO_TEST_DATABASE_URL"),
                     "Set WATCHDEMO_TEST_DATABASE_URL to run real PostgreSQL integration tests")
class PostgreSQLStorageTests(unittest.TestCase):
    def setUp(self):
        self.url = os.environ["WATCHDEMO_TEST_DATABASE_URL"]
        self.schema = "watchdemo_test_" + uuid4().hex
        self.repo = Repository(self.url, schema=self.schema)
        self.repo.migrate()
        self.temp = tempfile.TemporaryDirectory()
        self.directory = Path(self.temp.name) / "uploads"
        self.client = TestClient(create_app(repository=self.repo, upload_dir=self.directory))
        self.client.__enter__()

    def tearDown(self):
        self.client.__exit__(None, None, None)
        self.temp.cleanup()
        # Only the schema generated by this test is eligible for removal.
        self.assertTrue(self.schema.startswith("watchdemo_test_"))
        with self.repo.connect() as conn:
            conn.execute(sql.SQL("DROP SCHEMA {} CASCADE").format(sql.Identifier(self.schema)))

    def upload(self, filename="synthetic.dem", content=b"synthetic input"):
        frame = pd.DataFrame([{"name": p["name"], "steamid": p["steamid"],
                               "team_number": 3 if p["team"] == "CT" else 2} for p in PLAYERS])
        with patch("app.DemoParser") as parser:
            parser.return_value.parse_player_info.return_value = frame
            response = self.client.post("/demo/upload", files={"file": (filename, content)})
        self.assertEqual(response.status_code, 200, response.text)
        return response.json()

    def analyze(self, uploaded, result=None, player=0):
        with patch("app.analyze_demo", return_value=deepcopy(RESULT if result is None else result)) as analyze:
            response = self.client.post("/demo/analyze", json={
                "match_id": uploaded["match_id"], "steamid": PLAYERS[player]["steamid"],
            })
        self.assertEqual(response.status_code, 200, response.text)
        analyze.assert_called_once_with(str(self.directory / uploaded["filename"]), PLAYERS[player]["name"])
        return response.json()

    def test_migration_is_repeatable_and_preserves_rows(self):
        uploaded = self.upload()
        self.repo.migrate()
        self.repo.check_schema()
        self.assertIsNotNone(self.repo.get_match(uploaded["match_id"]))
        with self.repo.connect() as conn:
            self.assertEqual(conn.execute("SELECT count(*) AS n FROM schema_migrations").fetchone()["n"], 1)

    def test_migration_checksum_mismatch_is_detected(self):
        with self.repo.connect() as conn:
            conn.execute("UPDATE schema_migrations SET checksum = 'changed'")
        with self.assertRaisesRegex(RuntimeError, "checksum"):
            self.repo.migrate()
        with self.assertRaises(RuntimeError):
            self.repo.check_schema()

    def test_startup_requires_explicit_migration(self):
        repo = Repository(self.url, schema="watchdemo_test_" + uuid4().hex)
        with self.assertRaises(psycopg.errors.UndefinedTable):
            with TestClient(create_app(repository=repo, upload_dir=self.directory)):
                pass

    def test_full_result_reopens_after_new_app_and_input_deletion(self):
        uploaded = self.upload()
        analyzed = self.analyze(uploaded)
        (self.directory / uploaded["filename"]).unlink()
        with TestClient(create_app(repository=Repository(self.url, self.schema), upload_dir=self.directory)) as fresh:
            with patch("app.analyze_demo", side_effect=AssertionError("Must not reanalyze")), \
                 patch("app.DemoParser", side_effect=AssertionError("Must not reparse")):
                report = fresh.get(f"/reports/{analyzed['report_id']}").json()
                self.assertEqual(report["result"], RESULT)
                self.assertEqual(report["status"], "completed")
                self.assertEqual(report["format_version"], 1)
                self.assertEqual(report["match_id"], uploaded["match_id"])
                self.assertEqual(fresh.get("/reports").json()["reports"][0]["id"], analyzed["report_id"])
                self.assertEqual(fresh.get(f"/matches/{uploaded['match_id']}").json()["players"], PLAYERS)
            response = fresh.post("/demo/analyze", json={"match_id": uploaded["match_id"], "steamid": PLAYERS[0]["steamid"]})
            self.assertEqual(response.status_code, 410)

    def test_duplicate_original_filenames_do_not_overwrite_inputs(self):
        first = self.upload(content=b"first")
        second = self.upload(content=b"second")
        self.assertNotEqual(first["match_id"], second["match_id"])
        self.assertEqual((self.directory / first["filename"]).read_bytes(), b"first")
        self.assertEqual((self.directory / second["filename"]).read_bytes(), b"second")

    def test_reports_for_players_and_reanalysis_remain_independent(self):
        uploaded = self.upload()
        first = self.analyze(uploaded)
        other_result = deepcopy(RESULT)
        other_result["report"]["player"] = PLAYERS[1]["name"]
        other = self.analyze(uploaded, other_result, player=1)
        repeated = self.analyze(uploaded)
        self.assertEqual(len({first["report_id"], other["report_id"], repeated["report_id"]}), 3)
        self.assertEqual(self.client.get(f"/reports/{first['report_id']}").json()["result"], RESULT)
        self.assertEqual(self.client.get(f"/reports/{other['report_id']}").json()["result"], other_result)
        self.assertEqual(self.client.get("/matches").json()["matches"][0]["report_count"], 3)

    def test_history_is_paginated_filtered_and_excludes_snapshots(self):
        first = self.analyze(self.upload())
        second = self.analyze(self.upload())
        latest = self.client.get("/reports?limit=1").json()["reports"]
        self.assertEqual(latest[0]["id"], second["report_id"])
        self.assertNotIn("result", latest[0])
        older = self.client.get("/reports?limit=1&offset=1").json()["reports"]
        self.assertEqual(older[0]["id"], first["report_id"])
        filtered = self.client.get(f"/reports?match_id={first['match_id']}").json()["reports"]
        self.assertEqual([r["id"] for r in filtered], [first["report_id"]])
        self.assertEqual(len(self.client.get("/matches?limit=1&offset=1").json()["matches"]), 1)

    def test_analyzer_failure_persists_failed_report_without_partial_result(self):
        uploaded = self.upload()
        with patch("app.analyze_demo", side_effect=RuntimeError("private internal details")):
            response = self.client.post("/demo/analyze", json={"match_id": uploaded["match_id"], "steamid": PLAYERS[0]["steamid"]})
        self.assertEqual(response.status_code, 500)
        self.assertNotIn("private internal details", response.text)
        report_id = response.json()["detail"]["report_id"]
        report = self.client.get(f"/reports/{report_id}").json()
        self.assertEqual(report["status"], "failed")
        self.assertIsNone(report["result"])
        self.assertTrue(report["error"])
        self.assertTrue(report["finished_at"])

    def test_result_serialization_failure_is_not_saved_as_completed(self):
        uploaded = self.upload()
        with patch("app.analyze_demo", return_value={"bad": object()}):
            response = self.client.post("/demo/analyze", json={"match_id": uploaded["match_id"], "steamid": PLAYERS[0]["steamid"]})
        self.assertEqual(response.status_code, 500)
        self.assertEqual(self.client.get("/reports").json()["reports"][0]["status"], "failed")

    def test_database_write_failure_never_returns_analysis_success(self):
        uploaded = self.upload()
        with patch("app.analyze_demo", return_value=RESULT), \
             patch.object(self.repo, "complete_report", side_effect=psycopg.OperationalError("secret database credentials")):
            response = self.client.post("/demo/analyze", json={"match_id": uploaded["match_id"], "steamid": PLAYERS[0]["steamid"]})
        self.assertEqual(response.status_code, 503)
        self.assertNotIn("secret", response.text)
        self.assertEqual(self.client.get("/reports").json()["reports"][0]["status"], "failed")

    def test_invalid_upload_and_parse_failure_leave_no_files_or_matches(self):
        bad_extension = self.client.post("/demo/upload", files={"file": ("bad.txt", b"bad")})
        self.assertEqual(bad_extension.status_code, 400)
        with patch("app.DemoParser", side_effect=ValueError("bad input")):
            response = self.client.post("/demo/upload", files={"file": ("invalid.dem", b"bad")})
        self.assertEqual(response.status_code, 400)
        self.assertEqual(list(self.directory.iterdir()), [])
        self.assertEqual(self.client.get("/matches").json()["matches"], [])

    def test_upload_database_failure_cleans_only_new_temporary_file(self):
        existing = self.directory / "existing.dem"
        existing.write_bytes(b"untouched")
        with patch("app.DemoParser") as parser, \
             patch.object(self.repo, "create_match", side_effect=psycopg.OperationalError("unavailable")):
            parser.return_value.parse_player_info.return_value = pd.DataFrame([
                {"name": "test", "steamid": "123", "team_number": 2},
            ])
            response = self.client.post("/demo/upload", files={"file": ("test.dem", b"bad")})
        self.assertEqual(response.status_code, 503)
        self.assertEqual(list(self.directory.iterdir()), [existing])
        self.assertEqual(existing.read_bytes(), b"untouched")

    def test_upload_name_cannot_select_destination_path(self):
        uploaded = self.upload(filename="../../outside.dem")
        self.assertEqual(uploaded["original_filename"], "outside.dem")
        self.assertEqual(list(self.directory.iterdir()), [self.directory / uploaded["filename"]])
        self.assertFalse((self.directory.parent / "outside.dem").exists())
        for filename in ["../outside.dem", "C:\\outside.dem", "/tmp/outside.dem", "' OR 1=1 --"]:
            response = self.client.post("/demo/analyze", json={"filename": filename, "steamid": PLAYERS[0]["steamid"]})
            self.assertEqual(response.status_code, 404)

    def test_opaque_filename_request_remains_supported(self):
        uploaded = self.upload()
        with patch("app.analyze_demo", return_value=RESULT):
            response = self.client.post("/demo/analyze", json={"filename": uploaded["filename"], "steamid": PLAYERS[0]["steamid"]})
        self.assertEqual(response.status_code, 200)

    def test_unknown_ids_invalid_ids_player_and_pagination(self):
        for path in [f"/matches/{uuid4()}", f"/reports/{uuid4()}"]:
            self.assertEqual(self.client.get(path).status_code, 404)
        for path in ["/matches/not-a-uuid", "/reports/not-a-uuid", "/reports?limit=101",
                     "/reports?offset=-1", "/matches?limit=0", "/reports?match_id=bad"]:
            self.assertEqual(self.client.get(path).status_code, 422)
        uploaded = self.upload()
        response = self.client.post("/demo/analyze", json={"match_id": uploaded["match_id"], "steamid": "unknown"})
        self.assertEqual(response.status_code, 404)
        self.assertEqual(self.client.get("/reports").json()["reports"], [])

    def test_database_constraints_prevent_orphan_or_incomplete_completed_report(self):
        with self.assertRaises(psycopg.errors.ForeignKeyViolation):
            with self.repo.analysis(uuid4(), "123", "unknown"):
                pass
        uploaded = self.upload()
        with self.repo.analysis(uploaded["match_id"], "123", "unknown") as report_id:
            with self.assertRaises(psycopg.errors.CheckViolation):
                with self.repo.connect() as conn:
                    conn.execute("UPDATE reports SET status = 'completed', finished_at = now() WHERE id = %s", (report_id,))
            self.repo.complete_report(report_id, RESULT)

    def test_startup_recovers_interrupted_jobs_without_touching_live_jobs(self):
        uploaded = self.upload()
        interrupted_id = uuid4()
        with self.repo.connect() as conn:
            conn.execute("""INSERT INTO reports (id, match_id, steamid, player_name, status)
                VALUES (%s, %s, '123', 'interrupted', 'processing')""", (interrupted_id, uploaded["match_id"]))
        with self.repo.analysis(uploaded["match_id"], "123", "live") as live_id:
            with TestClient(create_app(repository=Repository(self.url, self.schema), upload_dir=self.directory)) as fresh:
                self.assertEqual(fresh.get(f"/reports/{interrupted_id}").json()["status"], "failed")
                self.assertEqual(fresh.get(f"/reports/{live_id}").json()["status"], "processing")
            self.repo.complete_report(live_id, RESULT)
        self.repo.recover_interrupted()
        self.assertEqual(self.repo.get_report(live_id)["result"], RESULT)

    def test_numpy_snapshot_roundtrips_through_postgresql_and_http(self):
        value = deepcopy(RESULT)
        value["stats"] = {"kills": np.int64(3), "missing": float("nan"), "ratio": np.float64(1.5)}
        response = self.analyze(self.upload(), result=value)
        self.assertEqual(response["result"]["stats"], {"kills": 3, "missing": None, "ratio": 1.5})
        self.assertEqual(self.client.get(f"/reports/{response['report_id']}").json()["result"], response["result"])

    def test_saved_result_survives_actual_server_process_restart(self):
        analyzed = self.analyze(self.upload())
        (self.directory / f"{analyzed['match_id']}.dem").unlink()
        with socket.socket() as sock:
            sock.bind(("127.0.0.1", 0))
            port = sock.getsockname()[1]
        code = (
            "import os,uvicorn; from app import create_app; from storage.repository import Repository; "
            "uvicorn.run(create_app(repository=Repository(os.environ['WATCHDEMO_TEST_DATABASE_URL'], "
            "os.environ['WATCHDEMO_TEST_SCHEMA']),upload_dir=os.environ['WATCHDEMO_TEST_UPLOADS']),"
            f"host='127.0.0.1',port={port},log_level='warning')"
        )
        env = {**os.environ, "WATCHDEMO_TEST_SCHEMA": self.schema,
               "WATCHDEMO_TEST_UPLOADS": str(self.directory)}
        results = []
        for _ in range(2):
            with tempfile.TemporaryFile() as log:
                process = subprocess.Popen([sys.executable, "-c", code], cwd=Path(__file__).resolve().parents[1],
                                           env=env, stdout=log, stderr=log,
                                           creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
                try:
                    with httpx.Client(base_url=f"http://127.0.0.1:{port}", trust_env=False, timeout=2) as http:
                        for attempt in range(100):
                            if process.poll() is not None:
                                log.seek(0)
                                self.fail(log.read().decode(errors="replace"))
                            try:
                                if http.get("/health").status_code == 200:
                                    break
                            except httpx.TransportError:
                                pass
                            time.sleep(0.1)
                        else:
                            self.fail("Server did not start")
                        response = http.get(f"/reports/{analyzed['report_id']}")
                        self.assertEqual(response.status_code, 200)
                        results.append(response.json())
                finally:
                    process.terminate()
                    process.wait(timeout=10)
        self.assertEqual(results[0], results[1])
        self.assertEqual(results[1]["result"], RESULT)


